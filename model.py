"""Patient-disjoint evaluation for two-hour glucose risk prediction."""
import json
from pathlib import Path
import joblib
import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier, HistGradientBoostingRegressor
from sklearn.metrics import roc_auc_score, average_precision_score, brier_score_loss, mean_absolute_error
from sklearn.model_selection import GroupShuffleSplit
from synthetic import FEATURES, add_targets, save_data


def train(output_dir=".", data_dir=".", n_patients=90, days=6, seed=42):
    ehr, series = save_data(data_dir, n_patients, days, seed)
    data = add_targets(ehr, series)
    if data["spike_2h"].nunique() != 2:
        raise ValueError("Synthetic dataset has only one target class; change seed or simulation parameters.")
    splitter = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=seed)
    train_ix, test_ix = next(splitter.split(data, groups=data["patient_id"]))
    tr, te = data.iloc[train_ix], data.iloc[test_ix]
    if tr["spike_2h"].nunique() != 2 or te["spike_2h"].nunique() != 2:
        raise ValueError("One patient-disjoint partition lacks both classes. Increase patient count.")
    classifier = HistGradientBoostingClassifier(max_iter=140, max_leaf_nodes=16, learning_rate=0.07, random_state=seed)
    regressor = HistGradientBoostingRegressor(max_iter=140, max_leaf_nodes=16, learning_rate=0.07, random_state=seed)
    classifier.fit(tr[FEATURES], tr["spike_2h"])
    regressor.fit(tr[FEATURES], tr["glucose_2h"])
    prob = classifier.predict_proba(te[FEATURES])[:, 1]
    predicted = regressor.predict(te[FEATURES])
    metrics = {
        "dataset": "100% algorithmically generated synthetic data; no patients or clinical validation",
        "prediction_horizon_hours": 2,
        "spike_threshold_mg_dl": 180,
        "n_train_patients": int(tr["patient_id"].nunique()),
        "n_test_patients": int(te["patient_id"].nunique()),
        "n_train_rows": len(tr),
        "n_test_rows": len(te),
        "test_spike_prevalence": round(float(te["spike_2h"].mean()), 4),
        "test_roc_auc": round(float(roc_auc_score(te["spike_2h"], prob)), 4),
        "test_average_precision": round(float(average_precision_score(te["spike_2h"], prob)), 4),
        "test_brier_score": round(float(brier_score_loss(te["spike_2h"], prob)), 4),
        "test_glucose_mae_mg_dl": round(float(mean_absolute_error(te["glucose_2h"], predicted)), 2),
        "split_method": "patient-disjoint GroupShuffleSplit; no patient overlap",
        "caveat": "Synthetic patterns were generated by hand-coded rules. Test performance cannot establish real-world clinical accuracy."
    }
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    joblib.dump({"classifier": classifier, "regressor": regressor, "features": FEATURES}, out / "glucotwin_models.joblib")
    (out / "metrics.json").write_text(json.dumps(metrics, indent=2))
    return metrics


def predict(bundle, row):
    X = row[bundle["features"]]
    return float(bundle["classifier"].predict_proba(X)[0, 1]), float(bundle["regressor"].predict(X)[0])
